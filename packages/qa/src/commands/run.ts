import type { RunReport } from "../report.js";
import type { Environment, RunContext } from "../types.js";
import type { ArgumentsCamelCase, Argv } from "yargs";
import { spawn } from "node:child_process";
import { existsSync } from "node:fs";
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join, relative, resolve } from "node:path";
import { getSmashConfig } from "@atomicsmash/smash-config";
import { ENVIRONMENTS, resolveEnvironment } from "../environment.js";
import type { JourneySource } from "../project.js";
import { findJourneys, getProjectPaths, loadQaConfig } from "../project.js";
import { RUN_CONTEXT_VARIABLE } from "../runtime/context.js";
import { createSessions } from "../session.js";

type RunArguments = {
	journeys: string[];
	env: Environment;
	browsers: "chromium" | "all";
	json: boolean;
};

/** Exit codes, so the skill can tell journey failures apart from setup problems. */
export const EXIT = { passed: 0, failed: 1, setup: 2 } as const;

export const command = "run [journeys..]";
export const describe =
	"Run journeys against an environment and write a report to .qa/results/.";

/**
 * Define the run command's arguments.
 */
export function builder(yargs: Argv) {
	return yargs
		.positional("journeys", {
			type: "string",
			array: true,
			default: [] as string[],
			describe:
				"Only run journeys whose name or file contains one of these. A .journey.ts path runs that file instead of qa/qa.config.ts",
		})
		.option("env", {
			alias: "e",
			choices: ENVIRONMENTS,
			default: "local",
			describe: "Environment from smash.config.ts to run against",
		})
		.option("browsers", {
			choices: ["chromium", "all"] as const,
			default: "chromium" as const,
			describe: "Run in Chromium only, or every desktop and mobile browser",
		})
		.option("json", {
			type: "boolean",
			default: false,
			describe: "Print the run report as JSON instead of Playwright output",
		});
}

/**
 * Turn a source path into a unique, flat spec file name.
 */
const toSpecName = (sourceFile: string) =>
	`${sourceFile
		.replace(/^\./, "")
		.replace(/[/\\]/g, "__")
		.replace(/\.ts$/, "")}.spec.ts`;

/**
 * Write a spec that imports a source module and registers the selected journeys from it.
 */
function toSpec(specsDir: string, { file, journeys }: JourneySource) {
	const isConfig = resolve(file) === getProjectPaths().qaConfigFile;
	const importPath = relative(specsDir, resolve(file)).replace(/\\/g, "/");
	const names = JSON.stringify(journeys.map(({ name }) => name));
	return `// Generated by smash-qa from ${file}. Do not edit.
import { registerJourneys } from "@atomicsmash/qa/runtime";
import source from "${importPath}";
registerJourneys(${isConfig ? "source.journeys ?? []" : "[source]"}, ${JSON.stringify(file)}, ${names});
`;
}

/**
 * Write the Playwright config and one spec per journey source into the git-ignored run directory.
 */
async function writeRunFiles(runDir: string, sources: JourneySource[]) {
	const specsDir = join(runDir, "specs");
	await rm(specsDir, { recursive: true, force: true });
	await mkdir(specsDir, { recursive: true });
	await writeFile(
		join(runDir, "playwright.config.mjs"),
		`// Generated by smash-qa. Do not edit; journeys are listed in qa/qa.config.ts.
import { createPlaywrightConfig } from "@atomicsmash/qa/playwright-config";
export default await createPlaywrightConfig();
`,
	);
	await Promise.all(
		sources.map((source) =>
			writeFile(
				join(specsDir, toSpecName(source.file)),
				toSpec(specsDir, source),
			),
		),
	);
}

/**
 * Run Playwright from the project's own install so journeys share its @playwright/test instance.
 */
function runPlaywright(
	configFile: string,
	context: RunContext,
	quiet: boolean,
) {
	const playwrightCli = createRequire(resolve("package.json")).resolve(
		"@playwright/test/cli",
	);
	return new Promise<number>((done, fail) => {
		spawn(process.execPath, [playwrightCli, "test", "--config", configFile], {
			stdio: ["ignore", quiet ? "ignore" : "inherit", "inherit"],
			env: {
				...process.env,
				[RUN_CONTEXT_VARIABLE]: JSON.stringify(context),
				...(quiet ? { SMASH_QA_QUIET: "1" } : {}),
			},
		})
			.on("error", fail)
			.on("exit", (code) => {
				done(code ?? EXIT.setup);
			});
	});
}

/**
 * Print a short summary of the report for people; the skill reads the JSON file.
 */
function printSummary(report: RunReport, reportFile: string) {
	const { passed, failed, skipped } = report.summary;
	console.log(
		`\n${report.env} (${report.baseURL}): ${passed.toString()} passed, ${failed.toString()} failed, ${skipped.toString()} skipped`,
	);
	report.journeys
		.filter(({ failure }) => failure)
		.forEach(({ name, failure }) => {
			console.log(
				`  ✗ ${name} — step ${((failure?.index ?? 0) + 1).toString()} "${failure?.description ?? ""}" [${failure?.failureClass ?? "unknown"}]`,
			);
		});
	console.log(`Report: ${reportFile}`);
}

/**
 * Run the selected journeys and exit with 0 (passed), 1 (journeys failed) or 2 (setup problem).
 */
export async function handler(args: ArgumentsCamelCase<RunArguments>) {
	try {
		const dotenv = await import("dotenv");
		dotenv.config({ quiet: true });

		const sources = await findJourneys(args.journeys);
		if (!sources.length) {
			throw new Error(
				"No journeys to run. List them in qa/qa.config.ts `journeys` (run `npx smash-qa init` to start) or check the filter.",
			);
		}
		const [smashConfig, qaConfig] = await Promise.all([
			getSmashConfig(2),
			loadQaConfig(),
		]);
		const { runDir } = getProjectPaths();
		const resultsDir = join(
			runDir,
			"results",
			`${args.env}-${new Date().toISOString().replace(/[:.]/g, "-")}`,
		);
		const environment = resolveEnvironment(args.env, smashConfig);
		const roles = sources.flatMap(({ journeys }) =>
			journeys.flatMap(({ as }) => (as ? [as] : [])),
		);
		const context: RunContext = {
			env: args.env,
			...environment,
			data: qaConfig.data?.[args.env] ?? {},
			sessions: roles.length
				? await createSessions(
						args.env,
						roles,
						smashConfig,
						environment.baseURL,
					)
				: {},
			browsers: args.browsers,
			timeout: qaConfig.timeout ?? 60_000,
			qaDir: runDir,
			resultsDir,
			reportFile: join(resultsDir, "report.json"),
		};

		await writeRunFiles(runDir, sources);
		const exitCode = await runPlaywright(
			join(runDir, "playwright.config.mjs"),
			context,
			args.json,
		);
		if (!existsSync(context.reportFile)) {
			throw new Error(
				`Playwright exited with code ${exitCode.toString()} before any journeys ran.`,
			);
		}
		const latestReport = join(runDir, "latest-report.json");
		await copyFile(context.reportFile, latestReport);
		const report = JSON.parse(
			await readFile(context.reportFile, "utf8"),
		) as RunReport;

		if (args.json) {
			console.log(JSON.stringify(report, null, "\t"));
		} else {
			printSummary(report, relative(process.cwd(), context.reportFile));
		}
		process.exitCode = report.summary.failed ? EXIT.failed : EXIT.passed;
	} catch (error) {
		console.error(error instanceof Error ? error.message : error);
		process.exitCode = EXIT.setup;
	}
}
